  // Takomillashtirilgan yangi o'zbek alifbosiga o'tkazish (O'->Ö, G'->Ğ, Sh->Ş, Ch->Ç)
  toNewUzbek(text) {
    if (!text || typeof text !== 'string') return text;
    if (/[\u0400-\u04FF]/.test(text)) return text;

    const protectedTokens = [];
    let s = text.replace(/(https?:\/\/[^\s"'<>]+|\b(?:English|Русский|Google|Firebase|Realtime|YouTube|Telegram|BarChart|Excel|CSV|HTML|PIN|SMS|ID)\b)/gi, (match) => {
      protectedTokens.push(match);
      return `__PROT_${protectedTokens.length - 1}__`;
    });

    // 1. O‘ / o‘ / O' / o' -> Ö / ö
    s = s.replace(/O['`‘’ʻʼ]/g, 'Ö').replace(/o['`‘’ʻʼ]/g, 'ö');
    // 2. G‘ / g‘ / G' / g' -> Ğ / ğ
    s = s.replace(/G['`‘’ʻʼ]/g, 'Ğ').replace(/g['`‘’ʻʼ]/g, 'ğ');
    // 3. Sh / sh / SH -> Ş / ş
    s = s.replace(/SH(?=[A-ZÖĞŞÇ\s.,!?:;\-\)]|$)/g, 'Ş')
         .replace(/Sh/g, 'Ş')
         .replace(/sh/g, 'ş');
    // 4. Ch / ch / CH -> Ç / ç
    s = s.replace(/CH(?=[A-ZÖĞŞÇ\s.,!?:;\-\)]|$)/g, 'Ç')
         .replace(/Ch/g, 'Ç')
         .replace(/ch/g, 'ç');

    s = s.replace(/__PROT_(\d+)__/g, (_, idx) => protectedTokens[Number(idx)] || '');
    return s;
  },

